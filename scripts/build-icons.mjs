import { readFile, readdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { runInNewContext } from 'node:vm';

const root = new URL('../', import.meta.url);
const output = new URL('assets/icons-20261015.js', root);
const excluded = new Set(['node_modules', 'dist', 'tests', 'scripts', 'docs', 'server', 'functions']);

async function htmlFiles(directory = root) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(entries.filter(({ name }) => !name.startsWith('.') && !excluded.has(name)).map(async (entry) => {
    const path = new URL(entry.name + (entry.isDirectory() ? '/' : ''), directory);
    if (entry.isDirectory()) return htmlFiles(path);
    return entry.name.endsWith('.html') ? [path] : [];
  }));
  return files.flat();
}

export async function buildIcons({ check = false } = {}) {
  // These states are inserted by home.js after playback, mute and retry actions.
  const names = new Set(['pause', 'play', 'rotate-ccw', 'volume-2', 'volume-x']);
  for (const file of await htmlFiles()) {
    const html = await readFile(file, 'utf8');
    for (const match of html.matchAll(/data-lucide=["']([a-z0-9-]+)["']/g)) names.add(match[1]);
  }
  // Use the reviewed, vendored Lucide release; rebuilding never needs a network request.
  const library = {};
  runInNewContext(await readFile(new URL('assets/lucide.min.js', root), 'utf8'), library);
  const icons = Object.fromEntries([...names].sort().map((name) => {
    const key = name.replace(/(^|-)([a-z0-9])/g, (_, separator, character) => character.toUpperCase());
    const nodes = library.lucide.icons[key];
    if (!nodes) throw new Error(`Unknown Lucide icon: ${name}`);
    return [name, nodes];
  }));
  const source = `/**
 * Lucide v1.8.0 SVG artwork, ISC license. See /assets/lucide.LICENSE.txt.
 * Generated by scripts/build-icons.mjs; rebuild when adding site icons.
 */
(() => {
  'use strict';
  const icons = ${JSON.stringify(icons)};
  const namespace = 'http://www.w3.org/2000/svg';
  const defaults = { xmlns: namespace, width: 24, height: 24, viewBox: '0 0 24 24', fill: 'none', stroke: 'currentColor', 'stroke-width': 2, 'stroke-linecap': 'round', 'stroke-linejoin': 'round' };
  const createNode = ([tag, attributes, children = []]) => {
    const node = document.createElementNS(namespace, tag);
    Object.entries(attributes).forEach(([name, value]) => node.setAttribute(name, String(value)));
    children.forEach((child) => node.appendChild(createNode(child)));
    return node;
  };
  const createIcons = () => {
    document.querySelectorAll('[data-lucide]').forEach((placeholder) => {
      if (placeholder.localName === 'svg') return;
      const name = placeholder.getAttribute('data-lucide');
      const artwork = icons[name];
      if (!artwork) return;
      const attributes = Object.fromEntries(Array.from(placeholder.attributes, ({ name, value }) => [name, value]));
      const accessible = Object.keys(attributes).some((key) => key.startsWith('aria-') || key === 'role' || key === 'title');
      const svg = createNode(['svg', {
        ...defaults,
        ...(accessible ? {} : { 'aria-hidden': 'true' }),
        ...attributes,
        class: ['lucide', 'lucide-' + name, attributes.class || ''].join(' ').trim(),
      }, artwork]);
      placeholder.replaceWith(svg);
    });
  };
  window.lucide = { createIcons };
})();
`;
  if (check) {
    if (await readFile(output, 'utf8').catch(() => '') !== source) {
      throw new Error('Site icon bundle is stale. Run node scripts/build-icons.mjs.');
    }
  } else {
    await writeFile(output, source);
  }
  return { icons: names.size, bytes: Buffer.byteLength(source), output: fileURLToPath(output) };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(await buildIcons({ check: process.argv.includes('--check') }));
}
